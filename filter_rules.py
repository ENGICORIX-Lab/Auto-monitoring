def score_title(title, keywords, excludes):
    """공고명 점수와 매칭된 키워드 목록을 반환합니다."""
    text = title.upper()
    score, hits, minus = 0, [], []
    # 긴 키워드를 먼저 확인해 '설계 및 제작'과 '제작'이 중복 가산되지 않게 합니다.
    consumed = text
    for kw, w in sorted(keywords.items(), key=lambda kv: -len(kv[0])):
        k = kw.upper()
        if k in consumed:
            score += w
            hits.append(kw)
            consumed = consumed.replace(k, " ")
    for kw, w in excludes.items():
        if kw.upper() in text:
            score += w
            minus.append(kw)
    return score, hits, minus
